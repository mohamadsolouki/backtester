const dictionaries: Record<Locale, Dictionary> = Object.fromEntries(
  locales.map((locale) => [locale, { ...baseTranslations, ...packs[locale], ...sentencePacks[locale] }])
) as Record<Locale, Dictionary>;

export function translate(locale: Locale, source: string) {
  if (locale === "en") return source;
  const normalized = source.replace(/\s+/g, " ").trim();
  if (!normalized) return source;
  const translated = dictionaries[locale][normalized];
  return translated ?? translateTemplate(locale, normalized) ?? source;
}

function word(locale: Locale, key: string) {
  return dictionaries[locale][key] ?? key;
}

function translateTemplate(locale: Locale, source: string) {
  const contextMatch = source.match(/^Context \((.+)\)$/);
  if (contextMatch) return `${word(locale, "Context")} (${contextMatch[1]})`;

  const reportMatch = source.match(/^(Daily|Weekly|Monthly) Report$/);
  if (reportMatch) return `${word(locale, reportMatch[1])} ${word(locale, "Reports")}`;

  const importMatch = source.match(/^Import (.+) Trades$/);
  if (importMatch) return `${word(locale, "Import Trades")} (${importMatch[1]})`;

  const activeMatch = source.match(/^(.+) active$/);
  if (activeMatch) return `${activeMatch[1]} ${word(locale, "Active").toLowerCase()}`;

  const samplesMatch = source.match(/^Samples (.+)$/);
  if (samplesMatch) return `${word(locale, "Samples")} ${samplesMatch[1]}`;

  const addQuotedMatch = source.match(/^\+ Add "(.+)"$/);
  if (addQuotedMatch) return `+ ${word(locale, "Add")} "${addQuotedMatch[1]}"`;

  const demoAccountMatch = source.match(/^(.+) (?:·|Â·) pre-loaded with sample trades$/);
  if (demoAccountMatch) return `${demoAccountMatch[1]} · ${word(locale, "pre-loaded with sample trades")}`;

  const demoSuffixMatch = source.match(/^(?:·|Â·) pre-loaded with sample trades$/);
  if (demoSuffixMatch) return ` · ${word(locale, "pre-loaded with sample trades")}`;

  return null;
}
