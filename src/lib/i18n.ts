export const locales = ["en", "fa", "ar"] as const;

export type Locale = (typeof locales)[number];

export const defaultLocale: Locale = "en";
export const localeCookieName = "trade-os-locale";

export const localeMeta: Record<Locale, { name: string; nativeName: string; dir: "ltr" | "rtl" }> = {
  en: { name: "English", nativeName: "English", dir: "ltr" },
  fa: { name: "Persian", nativeName: "فارسی", dir: "rtl" },
  ar: { name: "Arabic", nativeName: "العربية", dir: "rtl" },
};

export function isLocale(value: string | undefined | null): value is Locale {
  return !!value && (locales as readonly string[]).includes(value);
}

export function getLocaleDirection(locale: Locale) {
  return localeMeta[locale].dir;
}

